"""从 Alembic 迁移导出可重复生成的 PostgreSQL 建库 SQL。"""

import argparse
from io import StringIO
from pathlib import Path

from alembic import command
from alembic.config import Config

PROJECT_ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=PROJECT_ROOT / "ddl" / "postgresql" / "init.sql",
        help="输出路径，默认更新 ddl/postgresql/init.sql",
    )
    args = parser.parse_args()

    buffer = StringIO()
    config = Config(str(PROJECT_ROOT / "alembic.ini"), output_buffer=buffer)
    command.upgrade(config, "head", sql=True)
    header = (
        "-- Generated by: uv run python scripts/export_postgresql_schema.py\n"
        "-- Source: migrations/versions/. Do not edit this file directly.\n\n"
    )
    sql = "\n".join(line.rstrip() for line in buffer.getvalue().splitlines())
    args.output.resolve().write_text(header + sql.rstrip() + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
