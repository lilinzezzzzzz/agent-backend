@pytest.mark.asyncio
async def test_soft_delete(user_dao, db_session):
    """测试软删除"""
    user = User.create(username="del_me")
    active_user = User.create(username="keep_me")
    await user_dao.insert(user)
    await user_dao.insert(active_user)

    await user_dao.soft_delete(user)

    async with user_dao.read_session_provider() as session:
        active = (
            (await session.execute(user_dao.select_stmt().where(User.id == user.id)))
            .scalars()
            .first()
        )
        deleted = (
            (
                await session.execute(
                    user_dao.select_stmt(include_deleted=True).where(User.id == user.id)
                )
            )
            .scalars()
            .first()
        )
        deleted_by_filter = (
            (
                await session.execute(
                    user_dao.select_stmt(include_deleted=True).where(
                        User.deleted_at.is_not(None),
                        User.id == user.id,
                    )
                )
            )
            .scalars()
            .first()
        )
        active_by_filter = (
            (
                await session.execute(
                    user_dao.select_stmt(include_deleted=True).where(
                        User.deleted_at.is_(None),
                        User.id == user.id,
                    )
                )
            )
            .scalars()
            .first()
        )
        remaining_active = (
            (
                await session.execute(
                    user_dao.select_stmt(include_deleted=True).where(
                        User.deleted_at.is_(None),
                        User.id == active_user.id,
                    )
                )
            )
            .scalars()
            .first()
        )
        deleted_count = (
            await session.execute(
                user_dao.count_stmt(User.id, include_deleted=True).where(
                    User.deleted_at.is_not(None)
                )
            )
        ).scalar()
        active_count = (await session.execute(user_dao.count_stmt(User.id))).scalar()
        all_count = (
            await session.execute(user_dao.count_stmt(include_deleted=True))
        ).scalar()

    assert active is None
    assert deleted is not None
    assert deleted_by_filter is not None
    assert active_by_filter is None
    assert remaining_active is not None
    assert deleted_count == 1
    assert active_count == 1
    assert all_count == 2


